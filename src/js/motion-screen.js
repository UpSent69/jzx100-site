import gsap from "gsap";
import { ScrollTrigger } from "gsap/ScrollTrigger";
import { ease, isMobile, reducedMotion } from "./motion.js";

/**
 * Экран 3. Ролик идёт петлёй, пока экран в окне. Закреплённая секция ~250vh.
 *
 *   0.00 — 0.36  вход: кадр идёт сам, ничего больше не происходит
 *   0.36 — 0.54  подпись поднимается из-под края
 *   0.54 — 0.82  пауза: время прочитать
 *   0.82 — 1.00  сцена уходит в черноту (fadeScene)
 *
 * До этой правки сцена была устроена иначе: статичная фотография, боковой
 * разгон с наездом и перемотка ролика прокруткой. Заказчик попросил сделать
 * из этого обычную петлю, как на втором экране, — и от прежнего устройства
 * не осталось ничего, потому что держалось оно всё на перемотке:
 *
 *   * фотография была первым кадром ролика и существовала ради того, чтобы
 *     подмена одного слоя другим не читалась. Петле подменять нечего:
 *     кадр до загрузки показывает постер самого видео;
 *   * боковой сдвиг и наезд вели «разгон» вместо самой записи, которая
 *     стояла на месте, пока её не тронет скролл. Теперь движение в сцене
 *     даёт запись, и вести его второй раз преобразованием не нужно —
 *     тем более что кадр растянут с 1064 пикселей и лишнего увеличения
 *     не выдерживает;
 *   * под перемотку каждый кадр обязан быть ключевым. Четырнадцать секунд
 *     в 2560 стоили в такой кодировке двадцати шести мегабайт, петля —
 *     восьми.
 *
 * Прокрутке осталась подпись. Это и есть «одно событие на экран».
 */
export function initMotionScreen(root) {
  const video = root.querySelector("[data-motion-video]");
  const caption = root.querySelector("[data-motion-caption]");
  if (!video) return;

  if (reducedMotion) {
    // Сцены нет: остаётся постер, ролик не запускается
    gsap.set(caption, { opacity: 1 });
    root.style.height = "100svh";
    return;
  }

  const stage = root.querySelector(".motion__stage");

  // Ролик подтягивается на подходе, а не вместе со страницей: восемь мегабайт
  // в первом экране перевесили бы всё остальное вместе взятое. Два экрана
  // запаса — этого хватает, чтобы он успел прийти к началу сцены даже
  // на неспешной связи.
  let loaded = false;
  const load = () => {
    if (loaded || !video.dataset.src) return;
    loaded = true;
    video.preload = "auto";
    video.src = video.dataset.src;
    video.load();
  };

  ScrollTrigger.create({ trigger: root, start: "top 300%", once: true, onEnter: load });

  const tl = gsap.timeline({
    scrollTrigger: {
      trigger: root,
      start: "top top",
      end: "bottom bottom",
      pin: stage,
      pinSpacing: false,
      scrub: 1,
    },
  });

  // Пустой вход. Он не декоративный: шкала должна быть длиной ровно
  // в единицу, иначе доли на ней и доли прокрутки перестают совпадать
  // и подпись приходит не там, где написано.
  tl.to({}, { duration: 0.36 });

  // Короткая подпись поверх идущего кадра.
  if (caption) {
    tl.fromTo(
      caption.querySelectorAll(".reveal-line > *"),
      { yPercent: 110 },
      {
        yPercent: 0,
        duration: 0.18,
        ease: ease.out,
        stagger: isMobile ? 0 : 0.04,
      },
      0.36
    );
  }

  // Хвост до конца шкалы: после подписи остаётся почти половина секции
  // на чтение, и последняя пятая уходит в черноту вместе с fadeScene.
  tl.to({}, { duration: 0.46 }, 0.54);

  // Петля идёт, пока экран в окне, и встаёт за его пределами: за кадром
  // она только грела бы процессор. Точно так же сделан второй экран.
  // Загрузку дёргаем и отсюда. Один триггер на подходе к сцене на это
  // не годится: он срабатывает, когда прокрутка пересекает его границу,
  // а попасть в сцену можно и мимо неё — перезагрузкой на середине страницы,
  // переходом по якорю, прыжком полосы прокрутки. Тогда до сцены доезжали
  // с пустым видео, и на экране оставался один постер.
  const play = () => {
    load();
    video.play().catch(() => {});
  };
  ScrollTrigger.create({
    trigger: root,
    start: "top bottom",
    end: "bottom top",
    onEnter: play,
    onEnterBack: play,
    onLeave: () => video.pause(),
    onLeaveBack: () => video.pause(),
  });
}
