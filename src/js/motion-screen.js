import gsap from "gsap";
import { ScrollTrigger } from "gsap/ScrollTrigger";
import { ease, isMobile, reducedMotion, scrubVideo } from "./motion.js";

/**
 * Экран 3. Фото, переходящее в видео. Закреплённая секция ~320vh.
 *
 *   0.00 — 0.16  вход: фотография целым кадром, машина будто остановлена
 *                на полном ходу
 *   0.16 — 1.00  разгон: кадр ползёт вбок в сторону движения машины
 *   0.18 — 0.30  подмена: фотография сменяется роликом
 *   0.30 — 0.82  ролик, который ведёт прокрутка
 *   0.36 — 0.54  подпись
 *   0.54 — 0.82  пауза: время прочитать
 *   0.82 — 1.00  сцена уходит в черноту (fadeScene)
 *
 * Секция была 240vh — короче остальных, чтобы ощущалась скорость. Заказчик
 * попросил растянуть сам проезд, и длина пошла оттуда: на ролик теперь
 * приходится 52% от 220vh хода вместо 42% от 140vh — вдвое больше прокрутки
 * на те же две секунды. Вход при этом укорочен: держать неподвижный кадр
 * дольше полутора экранов незачем.
 *
 * Подмены не видно вообще: фотография — это первый кадр самого ролика,
 * снятый с уже пережатой копии. Меняются два одинаковых кадра, и меняться
 * начинает только то, что дальше делает ролик.
 *
 * Приём здесь принципиально другой, чем на первом экране: там была кромка,
 * тут — один непрерывный разгон, который ничем не прерывается.
 */
export function initMotionScreen(root) {
  const photo = root.querySelector("[data-motion-photo]");
  const video = root.querySelector("[data-motion-video]");
  const caption = root.querySelector("[data-motion-caption]");
  if (!photo || !video) return;

  if (reducedMotion) {
    // Сцены нет: остаётся один статичный кадр, ролик не запускается
    gsap.set(video, { opacity: 0 });
    gsap.set([photo, caption], { opacity: 1, x: 0, filter: "none" });
    root.style.height = "100svh";
    return;
  }

  // На узком экране машина покидает кадр раньше подмены, поэтому боковой
  // сдвиг уменьшен.
  const drift = isMobile ? 5 : 10;  // в процентах ширины кадра

  // Кадр начинается целым — ровно тем, что лежит в файле, без обрезки.
  // Раньше он стоял увеличенным на 1.42 всю сцену: от фотографии оставалась
  // середина, мост и обочина в кадр не попадали.
  //
  // Совсем без запаса нельзя: боковой сдвиг увёл бы кадр за край и открыл
  // пустую полосу. Поэтому запас не задаётся заранее, а нарастает — наезд
  // идёт сквозь всю сцену и обгоняет сдвиг на каждой её доле. На глаз это
  // не событие, а то, что кадр не стоит мёртво; целым он виден там, где
  // и должен, — на входе.
  // Сдвиг на 10% ширины открывает правый край, пока увеличение не дошло
  // до 1.20 — за каждый край выходит только половина прироста. 1.26 берётся
  // с небольшим запасом сверху, чтобы на краю не оставалось голой полосы,
  // которую смаз всё равно нечем было бы закрыть.
  const push = isMobile ? 1.16 : 1.26;
  gsap.set([photo, video], { scale: 1, transformOrigin: "50% 50%" });

  const stage = root.querySelector(".motion__stage");

  // Ролик подтягивается на подходе, а не вместе со страницей. Целиком: его
  // перематывает прокрутка, а по одним метаданным перематывать нечего.
  // Два экрана запаса — этого хватает, чтобы он успел прийти к началу сцены
  // даже на неспешной связи, и при этом он не мешает первому экрану.
  ScrollTrigger.create({
    trigger: root,
    start: "top 300%",
    once: true,
    onEnter: () => {
      if (!video.dataset.src) return;
      video.preload = "auto";
      video.src = video.dataset.src;
      video.load();
    },
  });

  const tl = gsap.timeline({
    scrollTrigger: {
      trigger: root,
      start: "top top",
      end: "bottom bottom",
      pin: stage,
      pinSpacing: false,
      scrub: 1,
    },
  });


  // Разгон идёт сквозной линией через оба слоя: фото и видео двигаются
  // как один кадр, поэтому в момент подмены ничего не дёргается.
  tl.fromTo(
    [photo, video],
    { xPercent: 0 },
    { xPercent: -drift, duration: 0.84, ease: "none" },
    0.16
  );

  // Наезд ведём с самого начала сцены и линейно: сдвиг стартует позже
  // и растёт медленнее, поэтому запаса хватает на каждой доле, а не только
  // в конце.
  tl.fromTo(
    [photo, video],
    { scale: 1 },
    { scale: push, duration: 1, ease: "none" },
    0
  );

  // Подмена фотографии роликом.
  //
  // Перехода здесь нет и не должно быть. Оба слоя показывают один и тот же
  // кадр — фотография вырезана из этого же ролика после пережатия, — поэтому
  // растворение меняет картинку саму на себя и на глаз не существует.
  // Держим его коротким и линейным: чем оно короче, тем меньше отрезок,
  // на котором два одинаковых слоя лежат друг на друге.
  tl.to(photo, { opacity: 0, duration: 0.12, ease: "none" }, 0.18);
  tl.fromTo(video, { opacity: 0 }, { opacity: 1, duration: 0.12, ease: "none" }, 0.18);

  // Короткая подпись поверх чистого видео.
  //
  // Раньше она поднималась на 0.72 и не успевала ничего: на этой доле снизу
  // уже наезжал следующий блок и срезал её. Теперь она встаёт сразу за подменой
  // и дальше держится до самого конца сцены.
  if (caption) {
    tl.fromTo(
      caption.querySelectorAll(".reveal-line > *"),
      { yPercent: 110 },
      {
        yPercent: 0,
        duration: 0.18,
        ease: ease.out,
        stagger: isMobile ? 0 : 0.04,
      },
      0.36
    );
  }

  // Ролик трогается только после того, как подмена закончилась.
  //
  // Раньше он шёл с 0.2 — то есть уже во время растворения. Фотография при этом
  // показывала первый кадр, а ролик под ней успевал уехать на четверть, и в
  // момент подмены картинка прыгала. Это и был тот самый видимый переход,
  // которого быть не должно: пока лежит фотография, ролик стоит на нуле,
  // и меняется ровно ничего.
  //
  // Заканчивается он на 0.82 — там, где сцена начинает уходить в черноту.
  // Дальше его хвост шёл бы уже под затуханием, и до конца кадр никто бы
  // не увидел: ролик обрывался бы на полуслове. Ради этого подмена и сдвинута
  // к началу — чтобы ходу ролика осталась половина сцены.
  scrubVideo(video, tl, 0.3, 0.52);
}
