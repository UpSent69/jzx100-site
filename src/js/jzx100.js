import gsap from "gsap";
import ScrollTrigger from "gsap/ScrollTrigger";
import { ease, isMobile, reducedMotion } from "./motion.js";

/**
 * Экран 2. Кадр — тихая петля из ночного паркинга, текстовый блок лежит
 * поверх него слева. Закреплённая секция ~250vh, три фазы:
 *
 *   0.00 — 0.05  вход: чистый кадр, ничего не происходит
 *   0.05 — 0.50  на кадре проступает текстовый блок
 *   0.50 — 1.00  стабилизация: время прочитать
 *
 * Отъезда камеры здесь больше нет. Он был рассчитан на фотографию и начинался
 * с приближения 1.25 — на ролике, который сам по себе мягче фотографии, это
 * приближение растягивало и без того небогатый кадр, и всё первое полслайда
 * картинка выглядела мыльной. Теперь кадр всё время стоит один к одному,
 * и единственное движение экрана — появление текста.
 */
export function initJzx100(root) {
  const frame = root.querySelector("[data-jzx-frame]");
  const copy = root.querySelector("[data-jzx-copy]");
  const video = root.querySelector("[data-jzx-video]");
  if (!frame) return;

  // Ролик тяжелее фотографии, которая здесь была, поэтому не грузится вовсе,
  // пока экран не подошёл. На узком экране берётся копия поменьше: на телефоне
  // разницы не видно, а вес вдвое ниже.
  if (video) {
    video.src = isMobile ? "/jzx100-garage-1280.mp4" : "/jzx100-garage.mp4";
    video.muted = true;
  }

  if (reducedMotion) {
    // Сцены нет — остаётся конечное состояние: кадр с текстом.
    // Ролик не идёт: движение здесь такое же движение, как и сама сцена.
    gsap.set(copy, { opacity: 1 });
    if (video) video.removeAttribute("src");
    return;
  }

  const stage = root.querySelector(".jzx__stage");

  // Файл начинает идти по сети, когда человек прошёл треть первого экрана:
  // с preload="none" он иначе тронулся бы только в момент запуска, и первые
  // кадры экран стоял бы на постере.
  //
  // Раньше здесь стояло "top 300%", как у экрана «Движение». Для него это
  // работает, а здесь нет: первый экран ровно 300vh, и до этой сцены от верха
  // страницы как раз три экрана — условие выполнялось сразу при загрузке,
  // и весь ролик попадал в вес первого экрана. Теперь до запуска остаётся
  // почти два экрана прокрутки — этого хватает и на неспешной связи.
  if (video) {
    ScrollTrigger.create({
      trigger: root,
      start: "top 180%",
      once: true,
      onEnter: () => {
        video.preload = "auto";
        video.load();
      },
    });
  }

  const tl = gsap.timeline({
    scrollTrigger: {
      trigger: root,
      start: "top top",
      end: "bottom bottom",
      pin: stage,
      pinSpacing: false,
      scrub: 1,
    },
  });


  // Короткая пауза на входе: кадр успевают увидеть чистым, без текста.
  tl.to({}, { duration: 0.05 });

  // Текст проступает на 45% секции. Ход намеренно длинный — на коротком
  // отрезке появление читалось бы как вспышка. К половине слайда он на месте.
  if (copy) {
    tl.to(copy, { opacity: 1, duration: 0.45, ease: ease.inOut }, 0.05);
  }

  // Пустая пауза до конца шкалы. Она не декоративная: прокрутка растягивается
  // на всю длину шкалы, а не на единицу, и без этого хвоста шкала кончалась
  // на 0.5 — сцена сжималась в первую половину секции, а вторая уходила
  // в пустоту. Теперь доли на шкале и доли прокрутки — одно и то же,
  // и после появления текста остаётся половина секции на чтение.
  tl.to({}, { duration: 0.5 }, 0.5);

  // Ролик идёт петлёй, пока экран в окне, и молчит за его пределами: за кадром
  // он только грел бы процессор. Прокрутка его не перематывает — движение
  // внутри кадра идёт своим ходом. Двадцать секунд перематывать было бы нечем:
  // под перемотку ролик кодируется сплошными ключевыми кадрами, и на такой
  // длине файл вырос бы в разы.
  if (video) {
    const play = () => video.play().catch(() => {});
    ScrollTrigger.create({
      trigger: root,
      start: "top bottom",
      end: "bottom top",
      onEnter: play,
      onEnterBack: play,
      onLeave: () => video.pause(),
      onLeaveBack: () => video.pause(),
    });
  }

  // Дальше кадр стоит до самого конца секции: текст можно прочитать,
  // а следующий экран наезжает поверх него сам.
  //
  // Здесь раньше был уход в глубину — кадр уменьшался и гас в ноль. Пока
  // он гас, следующая секция ещё не дошла до экрана, и между слайдами
  // оставался чёрный провал в целый экран. Уход убран: пустоты быть не должно.
}
