import gsap from "gsap";
import { ease, isMobile, reducedMotion } from "./motion.js";

/**
 * Экран 2. Готовая картинка: заголовок и текст уже впечатаны в кадр слева,
 * машина справа. Закреплённая секция ~250vh, три фазы:
 *
 *   0.00 — 0.05  вход: кадр приближен, центр смещён на машину,
 *                текстовый блок остаётся за краем экрана
 *   0.05 — 0.50  отъезд: камера долго отходит, в кадр входит левая часть,
 *                и тем же ходом на ней проступает текстовый блок
 *   0.50 — 1.00  стабилизация: полный кадр, время прочитать
 *
 * Отъезд занимает почти половину секции целиком, а не короткий кусок в её
 * середине: чем длиннее ход, тем меньше приходится на кадр прокрутки и тем
 * ровнее движение. К половине слайда кадр уже полный и текст читается.
 *
 * Исходник 1280×720, поэтому приближение на входе не больше 1.25 —
 * дальше начинается заметная потеря резкости.
 */
export function initJzx100(root) {
  const frame = root.querySelector("[data-jzx-frame]");
  const withText = root.querySelector("[data-jzx-text]");
  if (!frame) return;

  if (reducedMotion) {
    // Сцены нет — остаётся конечное состояние: полный кадр с текстом
    gsap.set(frame, { scale: 1, xPercent: 0, opacity: 1 });
    gsap.set(withText, { opacity: 1 });
    return;
  }

  // На вертикальном экране широкий кадр режется, и текст слева становится
  // нечитаем. Поэтому на мобильных начинаем сразу с полного кадра,
  // отъезд остаётся символическим.
  const zoom = isMobile ? 1.06 : 1.25;

  // Сдвиг центра на машину. Больше уводить нельзя: при увеличении 1.25
  // за краем кадра остаётся всего 12.5% ширины, дальше в кадр полез бы фон.
  // Из-за этого текстовый блок на входе уходит за край не целиком —
  // чтобы спрятать его полностью, нужно увеличение около 1.4, а это уже
  // заметная потеря резкости на исходнике 1280×720.
  const shift = isMobile ? 0 : -12;

  const stage = root.querySelector(".jzx__stage");

  const tl = gsap.timeline({
    scrollTrigger: {
      trigger: root,
      start: "top top",
      end: "bottom bottom",
      pin: stage,
      pinSpacing: false,
      scrub: 1,
    },
  });


  // Короткий вход: кадр стоит приближённым ровно столько, чтобы его успели
  // увидеть неподвижным. Дальше сразу начинается отъезд.
  tl.fromTo(
    frame,
    { scale: zoom, xPercent: shift },
    { scale: zoom, xPercent: shift, duration: 0.05, ease: "none" }
  );

  // Отъезд на 45% секции. Ход намеренно длинный: на короткий отрезок
  // приходилось по несколько процентов масштаба на кадр прокрутки, и движение
  // читалось рывком. Растянутое на полсекции, оно идёт почти незаметно —
  // кадр не «уезжает», а расходится.
  tl.to(frame, { scale: 1, xPercent: 0, duration: 0.45, ease: ease.inOut }, 0.05);

  // Текст проступает ровно вместе с отъездом: та же точка входа, та же
  // длительность, та же кривая. К половине слайда кадр полный, текст на месте.
  if (withText) {
    tl.to(withText, { opacity: 1, duration: 0.45, ease: ease.inOut }, 0.05);
  }

  // Пустая пауза до конца шкалы. Она не декоративная: прокрутка растягивается
  // на всю длину шкалы, а не на единицу, и без этого хвоста шкала кончалась
  // на 0.5 — сцена сжималась в первую половину секции, а вторая уходила
  // в пустоту. Теперь доли на шкале и доли прокрутки — одно и то же,
  // и после отъезда остаётся половина секции на чтение.
  tl.to({}, { duration: 0.5 }, 0.5);

  // Дальше кадр стоит до самого конца секции: текст можно прочитать,
  // а следующий экран наезжает поверх него сам.
  //
  // Здесь раньше был уход в глубину — кадр уменьшался и гас в ноль. Пока
  // он гас, следующая секция ещё не дошла до экрана, и между слайдами
  // оставался чёрный провал в целый экран. Уход убран: пустоты быть не должно.
}
