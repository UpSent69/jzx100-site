import gsap from "gsap";
import { ScrollTrigger } from "gsap/ScrollTrigger";
import Lenis from "lenis";

gsap.registerPlugin(ScrollTrigger);

/** Пользователь просил не двигать — тогда сцен нет, только простые переходы. */
export const reducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;

/** Мобильная логика — не уменьшенная копия десктопной, а отдельная ветка. */
export const isMobile = window.matchMedia("(max-width: 860px)").matches;

/** Длительности берём из токенов, чтобы CSS и GSAP не разъезжались. */
const css = getComputedStyle(document.documentElement);
const seconds = (name) => parseFloat(css.getPropertyValue(name)) || 0;

export const dur = {
  hover: seconds("--dur-hover"),
  reveal: seconds("--dur-reveal"),
  scene: seconds("--dur-scene"),
};

/* Тяжёлые кривые: долгий разгон, долгое торможение, ни одного отскока.
   GSAP не принимает cubic-bezier строкой, поэтому здесь его собственные
   имена — подобраны под те же кривые, что записаны в токенах CSS. */
export const ease = {
  out: "power3.out",
  inOut: "power2.inOut",
};

let lenis = null;

/** Доступ к экземпляру: он появляется только после initScroll и не в reduced-motion. */
export const lenisInstance = () => lenis;

/**
 * Инерционная прокрутка и её сшивка со ScrollTrigger.
 *
 * Lenis двигает страницу сам, поэтому ScrollTrigger нельзя оставлять на
 * нативном событии scroll — он бы считал позицию с опозданием на кадр.
 * Обновляем его из колбэка Lenis, а сам Lenis крутим тикером GSAP,
 * чтобы на кадр приходился ровно один пересчёт.
 */
export function initScroll() {
  if (reducedMotion) {
    // Сглаженная прокрутка — это тоже движение. Оставляем нативную.
    return null;
  }

  // Пересчёт длины закреплённых секций при каждом изменении высоты окна
  // выключен: на телефоне адресная строка прячется и появляется на ходу,
  // и сцена от этого прыгает посреди движения.
  ScrollTrigger.config({ ignoreMobileResize: true });

  lenis = new Lenis({
    // Чем меньше lerp, тем дольше страница догоняет колесо. Это и есть
    // инерция: движение не начинается и не заканчивается вместе с рукой.
    //
    // Было 0.045 — страница отставала от руки почти на секунду, и поверх этого
    // сцены шли со своим запаздыванием. Два запаздывания складывались, и любой
    // пропущенный кадр читался как рывок: глаз ждал одного, а получал другое.
    // 0.07 — всё ещё заметная инерция, но страница идёт за рукой, а не следом.
    lerp: 0.07,
    wheelMultiplier: 0.8,
    touchMultiplier: 1.2,
    smoothWheel: true,
    syncTouch: true,      // на тач-экранах инерция тоже наша, а не системная
  });

  lenis.on("scroll", ScrollTrigger.update);

  gsap.ticker.add((time) => lenis.raf(time * 1000));
  gsap.ticker.lagSmoothing(0);

  // Заметка на будущее: ScrollTrigger.defaults({ scrub }) здесь не ставить.
  // Его наследуют и появления элементов, а появление со scrub не доигрывает
  // до конца — элемент навсегда остаётся сдвинутым на десяток пикселей.
  // Каждая сцена задаёт scrub сама.

  // Прокруткой распоряжается Lenis, поэтому window.scrollTo снаружи не работает.
  // Ручка нужна снималке кадров из tools/shots.mjs, чтобы вставать в заданную
  // точку сцены.
  window.__lenis = lenis;

  return lenis;
}

/**
 * Строки поднимаются из-под невидимого края, друг за другом.
 * На мобильных очерёдность снимается — появляются разом.
 */
export function revealLines(root, { stagger = 0.08 } = {}) {
  const lines = root.querySelectorAll(".reveal-line > *");
  if (!lines.length) return;

  if (reducedMotion) {
    gsap.set(lines, { yPercent: 0, opacity: 1 });
    return;
  }

  gsap.fromTo(
    lines,
    { yPercent: 110 },
    {
      yPercent: 0,
      duration: dur.reveal,
      ease: ease.out,
      stagger: isMobile ? 0 : stagger,
      scrollTrigger: { trigger: root, start: "top 80%", once: true },
    }
  );
}

/**
 * Сцена появляется из черноты и в неё же уходит.
 *
 * Между слайдами теперь пустота, а слайд — это кадр во весь экран. Его верхняя
 * кромка, въезжая, была бы резкой горизонтальной чертой на чёрном. Растворять
 * её маской, как раньше, больше не во что: под ней не предыдущий слайд, а фон
 * страницы. Зато и не нужно — достаточно вести прозрачность всей сцены.
 *
 * Расчёт на совпадение: пока кромка на экране, сцена почти прозрачна, а к
 * полной непрозрачности она приходит уже развёрнутой на весь экран. Кромку
 * не видно ни разу, хотя ничего специально для неё не делается.
 *
 * Ведём прозрачность, а не маску: это одно число на слой, самая дешёвая
 * анимация из возможных, — а поверх идут сцены, которым нужен каждый кадр.
 *
 * Закреплённые сцены и обычный блок ведут себя по-разному, и одной геометрией
 * их не покрыть. Закреплённая сцена стоит на месте, пока идёт её собственная
 * шкала, поэтому уход у неё считается от хода закрепления и обязан закончиться
 * до открепления. Обычный блок никуда не прикреплён — он просто проезжает через
 * экран, и его появление с уходом привязаны к тому, где сейчас его кромки.
 *
 * @param {HTMLElement} section секция
 * @param {HTMLElement} stage   её сцена
 * @param {object} opts         fadeIn/fadeOut — с какой стороны растворять,
 *                              pinned — закреплена ли сцена
 */
export function fadeScene(section, stage, { fadeIn = true, fadeOut = true, pinned = true } = {}) {
  if (!stage || reducedMotion) return;

  if (fadeIn) {
    gsap.fromTo(
      stage,
      { opacity: 0 },
      {
        opacity: 1,
        ease: "none",
        // У закреплённой сцены — ровно то время, пока её верхняя кромка
        // на экране: от касания низа окна до выхода на самый верх. К концу
        // этого хода сцена занимает весь экран, кромки уже нет.
        //
        // У обычного блока так нельзя: он не встаёт на месте, а едет дальше,
        // и к моменту «top top» половина его уже ушла бы за верх. Поэтому
        // он набирает непрозрачность быстрее и дальше едет через экран целым.
        scrollTrigger: {
          trigger: section,
          start: "top bottom",
          end: pinned ? "top top" : "top 40%",
          scrub: true,
        },
      }
    );
  }

  if (fadeOut) {
    gsap.fromTo(
      stage,
      { opacity: 1 },
      {
      opacity: 0,
      ease: "none",
      // Начальное значение задано явно, и это не придирка к стилю.
      //
      // С обычным .to() GSAP запоминает начало сам — тем, что увидит на слое
      // в момент первой отрисовки. Слоем в это время распоряжается ещё
      // и появление, и пересчёт при refresh; стоило уходу один раз записать
      // себе ноль, и дальше он гнал ноль в ноль. Сцена гасла задолго до своей
      // точки, а при прокрутке назад не возвращалась вовсе — оставалась чёрной
      // навсегда. Именно это и выглядело как обрыв.
      //
      // immediateRender: false — чтобы этот твин не написал слою единицу
      // прямо при создании и не перебил появление, которое ведёт тот же слой.
      immediateRender: false,
      // Уход заканчивается там, где кончается закрепление, — то есть до того,
      // как в кадре появится чёрная пауза.
      //
      // Раньше он с этой точки только начинался и шёл целый экран. Пауза
      // въезжала снизу, когда предыдущий слайд был ещё почти непрозрачным,
      // и между ними стояла резкая горизонтальная черта. Теперь к моменту
      // её появления гасить уже нечего: сцена растворяется на месте, пока
      // держится закреплённой, а вверх уходит пустой.
      //
      // Длина считается от хода сцены, а не от высоты окна. От окна нельзя:
      // ход у сцен разный, и одна и та же полоса в пикселях у длинной сцены
      // будет хвостиком, а у короткой (третий экран, да ещё на телефоне)
      // съест половину — подпись погаснет раньше, чем её прочитают.
      // Потолок в полэкрана — чтобы у самой длинной сцены уход не растянулся
      // на целую вечность.
      //
      // Обычному блоку эта арифметика не подходит: он ростом с экран, хода
      // закрепления у него попросту нет — считать нечего, и уход выродился бы
      // в мгновенный скачок. Он гаснет, пока его нижняя кромка идёт по экрану
      // снизу вверх, и к моменту, когда блок покидает экран, его уже нет.
      scrollTrigger: {
        trigger: section,
        start: pinned
          ? () => {
              const span = Math.max(1, section.offsetHeight - window.innerHeight);
              const len = Math.min(window.innerHeight * 0.5, span * 0.18);
              return `bottom bottom+=${Math.round(len)}`;
            }
          : "bottom 60%",
        end: pinned ? "bottom bottom" : "bottom top",
        scrub: true,
        // Точку начала считает функция, и на каждом пересчёте её надо звать
        // заново — иначе после смены размера окна уход останется привязанным
        // к прежней высоте.
        invalidateOnRefresh: true,
      },
      }
    );
  }
}

/**
 * Ролик, который перематывает прокрутка.
 *
 * Ничего не проигрывается само по себе: положение в ролике — это положение
 * на странице. Прокрутил назад — отмотался назад.
 *
 * Ролики под это пережаты со сплошными ключевыми кадрами
 * (tools/encode_video.sh), иначе перемотка липнет к опорным точкам
 * и картинка меняется рывками.
 *
 * @param {HTMLVideoElement} video
 * @param {gsap.core.Timeline} tl   шкала сцены
 * @param {number} at               доля сцены, с которой ролик начинает идти
 * @param {number} span             какую долю сцены он занимает
 */
export function scrubVideo(video, tl, at = 0, span = 1) {
  if (!video) return;

  video.muted = true;
  video.playsInline = true;
  video.loop = false;
  video.pause();

  const FRAME = 1 / 60;   // ролики пережаты в шестьдесят кадров
  const STUCK = 400;      // мс: столько ждём ответа, дальше считаем, что его не будет

  const head = { t: 0 };
  let duration = 0;

  let want = -1;          // куда просят встать
  let asked = 0;          // когда попросили; 0 — не просили

  const ready = () => {
    duration = video.duration || 0;
  };
  if (video.readyState >= 1) ready();
  video.addEventListener("loadedmetadata", ready, { once: true });

  /**
   * Перемотка идёт по одной за раз.
   *
   * Раньше время назначалось на каждом кадре анимации. Браузер отрабатывает
   * перемотку не мгновенно, запросы копились в очереди, и картинка ползла
   * следом за прокруткой ступеньками, отставая тем сильнее, чем быстрее крутят.
   * Теперь запрос уходит только после ответа на предыдущий, а промежуточные
   * положения не копятся, а перетирают друг друга: браузер всегда едет к тому
   * месту, где прокрутка находится сейчас, а не к тому, где она была.
   */
  const pump = () => {
    if (want < 0 || !duration || video.readyState < 2) return;
    // Ответа ещё нет — ждём, но не вечно: если перемотку отменили или потеряли,
    // без этого срока сцена встала бы намертво
    if (asked && performance.now() - asked < STUCK) return;
    // Шаг мельче половины кадра глазом не различить, а стоит столько же,
    // сколько любой другой
    if (Math.abs(video.currentTime - want) < FRAME / 2) return;

    asked = performance.now();
    // fastSeek не выравнивает картинку по опорным кадрам — при сплошных
    // ключевых он попадает точно и обходится дешевле обычного присваивания
    if (video.fastSeek) video.fastSeek(want);
    else video.currentTime = want;
  };

  video.addEventListener("seeked", () => {
    asked = 0;
    pump();
  });

  tl.to(
    head,
    {
      t: 1,
      duration: span,
      ease: "none",
      onUpdate: () => {
        // Последний кадр не берём: на самом конце некоторые сборщики
        // отдают пустоту вместо картинки
        want = Math.min(head.t * duration, Math.max(0, duration - 0.05));
        pump();
      },
    },
    at
  );
}
