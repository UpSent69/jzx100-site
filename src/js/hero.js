import gsap from "gsap";
import { ScrollTrigger } from "gsap/ScrollTrigger";
import { ease, isMobile, reducedMotion, scrubVideo } from "./motion.js";

/**
 * Экран 1. Закреплённая секция длиной ~460vh, четыре фазы:
 *
 *   0.00 — 0.12  статичный кадр, ничего не двигается
 *   0.12 — 0.34  буквы гаснут и уходят вверх, по очереди слева направо
 *   0.34 — 0.44  пауза: только машина и фон, кадр едва приближается
 *   0.44 — 1.00  ролик открывается кромкой снизу вверх и идёт до конца
 *
 * Доли смещены к началу нарочно. В абсолютной прокрутке первые три фазы
 * занимают примерно столько же, сколько занимали раньше, а весь прирост
 * длины секции достался ролику: на него теперь приходится больше половины
 * хода вместо трети, и он успевает пройти целиком, а не промелькнуть.
 *
 * Пауза в середине обязательна: без неё уход букв и появление видео
 * сливаются в одно неразборчивое движение.
 */
export function initHero(root) {
  const stage = root.querySelector(".hero__stage");
  const plate = root.querySelector("[data-hero-plate]");
  const car = root.querySelector("[data-hero-car]");
  const video = root.querySelector("[data-hero-video]");
  const lettersLayer = root.querySelector("[data-hero-letters]");
  const letters = [...root.querySelectorAll("[data-letter]")];
  const caption = root.querySelector(".hero__caption");
  const backdrop = root.querySelector(".hero__backdrop");

  if (reducedMotion) {
    // Сцены нет. Остаётся исходная композиция целиком и неподвижно:
    // фоновый ролик — тоже движение, поэтому он не запускается вовсе.
    video.removeAttribute("autoplay");
    video.pause();
    root.style.height = "100svh";
    return;
  }

  const tl = gsap.timeline({
    scrollTrigger: {
      trigger: root,
      start: "top top",
      end: "bottom bottom",
      pin: stage,
      pinSpacing: false,
      scrub: 1,
    },
  });

  // --- фаза 1: пауза. Ничего, кроме ожидания ---
  tl.to({}, { duration: 0.12 });

  // --- фаза 2: уход надписи ---
  // Буквы гаснут и уходят вверх с лёгким размытием. На мобильных очерёдности
  // нет: на узком экране разбег читается как рассинхрон, а не как замысел.
  tl.to(
    letters,
    {
      yPercent: -72,
      opacity: 0,
      duration: 0.22,
      ease: ease.inOut,
      // Разбег должен читаться как очередь, а не как дрожь: при 0.035
      // знаки уходили почти вместе.
      stagger: isMobile ? 0 : { each: 0.035, from: "start" },
    },
    0.12
  );

  // Размытие ведём на общем слое, а не на каждом знаке. Шесть отдельных
  // фильтров пересчитывались каждый кадр и роняли сцену до двадцати кадров
  // в секунду; общий — это один проход. Очередь всё равно читается,
  // её задают сдвиг и прозрачность.
  //
  // Радиус небольшой намеренно. Слой размером во весь экран, и размытие на нём
  // пересчитывается каждый кадр: при 18 пикселях на этой фазе сцена проваливалась
  // до тринадцати кадров в секунду — уход букв, то есть первое движение на сайте,
  // выглядел рваным. Восьми хватает: размытие здесь и задумано лёгким,
  // уход держат сдвиг и прозрачность.
  tl.fromTo(
    lettersLayer,
    { filter: "blur(0.4px)" },
    { filter: "blur(8px)", duration: 0.22, ease: ease.inOut },
    0.12
  );

  // Знаки расшифровываем заранее. Иначе первый же кадр, на котором они
  // двигаются, ждёт распаковки шести картинок — и первое движение на сайте
  // начинается с провала.
  letters.forEach((l) => l.decode?.().catch(() => {}));

  // Подпись уходит вместе с надписью — она из того же слоя смысла,
  // но чуть позже: иначе низ кадра пустеет раньше, чем верх
  tl.to(caption, { opacity: 0, duration: 0.16, ease: ease.inOut }, 0.15);

  // --- фаза 3: пауза, кадр едва заметно приближается ---
  // Наезд идёт сквозь всю сцену, поэтому он не читается как отдельное
  // событие — только как то, что кадр не стоит мёртво.
  tl.fromTo(
    [plate, car],
    { scale: 1 },
    { scale: 1.06, duration: 0.32, ease: "none" },
    0.12
  );

  // --- фаза 4: смена фотографии на видео ---
  // Раньше здесь было растворение — оно выбивалось из общего языка: все
  // остальные стыки на сайте открываются снизу вверх мягкой кромкой. Теперь
  // так же и здесь: кромка идёт от нижнего края к верхнему, за ней ролик,
  // перед ней фотография. Глубина растяжки и ход — те же, что на стыке слайдов
  // (подробности в screen-hero.css, где эта кромка и собрана).
  //
  // Масштаб ролик подхватывает там же, где его оставила фотография, и дальше
  // спокойно доводит до единицы — это читается как продолжение того же наезда.
  //
  // Кромка работает только там, где фотография и ролик стоят одинаково, —
  // то есть на широком экране. На вертикальном фотография вписана по ширине
  // и стоит в рамке, а ролик занимает экран целиком; кромка провела бы черту
  // между двумя разными крупностями одного и того же кадра. Там остаётся
  // растворение: оно эту разницу не показывает.
  if (isMobile) {
    tl.to([plate, car, backdrop], { opacity: 0, duration: 0.16, ease: ease.inOut }, 0.44);
    tl.fromTo(
      video,
      { opacity: 0, scale: 1.06 },
      { opacity: 1, duration: 0.16, ease: ease.inOut },
      0.44
    );
  } else {
    tl.fromTo(
      video,
      { opacity: 1, scale: 1.06, "--wipe": "100svh" },
      { "--wipe": "-34svh", duration: 0.16, ease: "none" },
      0.44
    );

    // Фотография уже полностью закрыта роликом — снимаем её со сцены, чтобы
    // не держать под ним три лишних слоя. Это не событие, а уборка,
    // поэтому мгновенно и без кривой.
    tl.set([plate, car, backdrop], { opacity: 0 }, 0.62);
  }

  tl.to(video, { scale: 1, duration: 0.56, ease: ease.out }, 0.44);

  // Ролик ведёт прокрутка, и трогается он только после того, как растворение
  // закончилось, — иначе подмена читается двоением.
  //
  // Заканчивается он не в конце шкалы, а там, где сцена начинает уходить
  // в черноту (fadeScene берёт под уход последние 14% этой секции). Если гнать
  // ролик до самого конца, его хвост проигрывается уже под затуханием: до конца
  // его никто не видит, и выглядит это как оборванный на полуслове кадр.
  scrubVideo(video, tl, 0.54, 0.32);
}
