#!/usr/bin/env bash
# Пережатие роликов для веба.
#
# Фоновые ролики первого и третьего экрана не проигрываются сами — их
# перематывает прокрутка. Из этого следуют два решения:
#
#   * ход вперёд-назад в файл больше не запекается. Он был нужен, чтобы
#     не был виден стык петли; при перемотке прокруткой петли нет вовсе,
#     назад ролик отматывает сам скролл. Файл от этого вдвое легче.
#   * ключевой кадр ставится часто. Перемотка попадает на ближайший ключевой,
#     и при обычном интервале в две-три секунды картинка менялась бы рывками
#     через раз.
#
set -e

FFDIR="/c/Users/fallm/AppData/Local/Microsoft/WinGet/Packages/Gyan.FFmpeg_Microsoft.Winget.Source_8wekyb3d8bbwe/ffmpeg-9.0-full_build/bin"
[ -d "$FFDIR" ] && export PATH="$FFDIR:$PATH"

A="$(cd "$(dirname "$0")/.." && pwd)/assets"
W="$A/web"
mkdir -p "$W"

# Каждый кадр — ключевой.
#
# Перемотка всегда попадает на ближайший ключевой кадр. При интервале даже
# в три кадра браузер на каждый шаг прокрутки доставал опорный кадр и достраивал
# от него — картинка менялась ступеньками и отставала от руки. Со сплошными
# ключевыми любой кадр достаётся сразу и целиком, и перемотка идёт ровно.
#
# Платим размером: ролик тяжелеет примерно вдвое. Для двухсекундного куска это
# полтора-три мегабайта — цена, которую видно на счётчике и не видно на глаз,
# в отличие от рывков.
KEYS="-g 1 -keyint_min 1 -sc_threshold 0"

# Оба исходника сняты в 30 кадрах — для перемотки прокруткой этого мало.
# Тридцать кадров на двухсекундный ролик — это шестьдесят разных картинок
# на весь ход сцены, и шаг между ними виден как ступенька. Достраиваем до
# шестидесяти: разных картинок вдвое больше, шаг вдвое мельче.
#
# Прежнему ролику третьего экрана достройка была противопоказана — межкадровый
# расчёт рвал фон блоками на кустах и разметке. Нынешний проезд считается чисто,
# проверено покадрово, поэтому достраиваются оба.
SMOOTH="minterpolate=fps=60:mi_mode=mci:mc_mode=aobmc:me_mode=bidir:vsbmc=1"

# --- первый экран: 60 кадров, под перемотку, без звука ---
# 1280, а не 1600: этот ролик грузится до входа на сайт, и его вес — это время,
# которое человек смотрит на прелоадер. Съёмка сверху по ровному асфальту,
# мелкой фактуры в кадре нет, разницы между 1280 и 1600 на глаз не видно.
echo "hero-bg: достраиваю до 60 кадров…" >&2
ffmpeg -y -v error -i "$A/hero-bg.mp4" -an \
  -vf "$SMOOTH,scale=1280:-2" \
  -c:v libx264 -preset slow -crf 26 -pix_fmt yuv420p -profile:v high \
  $KEYS -movflags +faststart "$W/hero-bg.mp4"

# --- экран «Движение»: 60 кадров, под перемотку, без звука ---
# Исходник — motion-run.mp4, проезд 1920×1080. Здесь 1600: кадр показывается
# с увеличением до 1.26, машина в фокусе, и мягкость видна сразу. Грузится он
# уже за первым экраном, на прелоадер не влияет.
echo "motion-bg: достраиваю до 60 кадров…" >&2
ffmpeg -y -v error -i "$A/motion-run.mp4" -an \
  -vf "$SMOOTH,scale=1600:-2" \
  -c:v libx264 -preset slow -crf 26 -pix_fmt yuv420p -profile:v high \
  $KEYS -movflags +faststart "$W/motion-bg.mp4"

# Статичный кадр, с которого сцена открывается, — это первый кадр самого ролика,
# и снят он не с оригинала, а с уже пережатой копии: тогда у фотографии и видео
# совпадают не только композиция, но и цвет после кодека. Подмена одного слоя
# на другой не видна вовсе — меняются пиксель в пиксель одинаковые кадры.
#
# Пересобирается вместе с роликом, иначе после замены остался бы старый кадр.
for w in 1600 1280 828; do
  sfx=""; [ "$w" -ne 1600 ] && sfx="-$w"
  ffmpeg -y -v error -i "$W/motion-bg.mp4" -frames:v 1 -vf "scale=$w:-2" -q:v 80 "$W/motion-open$sfx.webp"
  ffmpeg -y -v error -i "$W/motion-bg.mp4" -frames:v 1 -vf "scale=$w:-2" -q:v 4  "$W/motion-open$sfx.jpg"
done

# --- карточки: звук сохраняем, длину не трогаем ---
for n in 1 2; do
  ffmpeg -y -v error -i "$A/card-$n.mp4" \
    -c:v libx264 -preset slow -crf 27 -pix_fmt yuv420p -profile:v high \
    -c:a aac -b:a 96k -ac 2 -movflags +faststart "$W/card-$n.mp4"
done

ls -la "$W"/*.mp4
echo DONE
