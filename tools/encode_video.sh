#!/usr/bin/env bash
# Пережатие роликов для веба.
#
# Фоновые ролики первого и третьего экрана не проигрываются сами — их
# перематывает прокрутка. Из этого следуют два решения:
#
#   * ход вперёд-назад в файл больше не запекается. Он был нужен, чтобы
#     не был виден стык петли; при перемотке прокруткой петли нет вовсе,
#     назад ролик отматывает сам скролл. Файл от этого вдвое легче.
#   * ключевой кадр ставится часто. Перемотка попадает на ближайший ключевой,
#     и при обычном интервале в две-три секунды картинка менялась бы рывками
#     через раз.
#
set -e

FFDIR="/c/Users/fallm/AppData/Local/Microsoft/WinGet/Packages/Gyan.FFmpeg_Microsoft.Winget.Source_8wekyb3d8bbwe/ffmpeg-9.0-full_build/bin"
[ -d "$FFDIR" ] && export PATH="$FFDIR:$PATH"

A="$(cd "$(dirname "$0")/.." && pwd)/assets"
W="$A/web"
mkdir -p "$W"

# Каждый кадр — ключевой.
#
# Перемотка всегда попадает на ближайший ключевой кадр. При интервале даже
# в три кадра браузер на каждый шаг прокрутки доставал опорный кадр и достраивал
# от него — картинка менялась ступеньками и отставала от руки. Со сплошными
# ключевыми любой кадр достаётся сразу и целиком, и перемотка идёт ровно.
#
# Платим размером: ролик тяжелеет примерно вдвое. Для двухсекундного куска это
# полтора-три мегабайта — цена, которую видно на счётчике и не видно на глаз,
# в отличие от рывков.
KEYS="-g 1 -keyint_min 1 -sc_threshold 0"

# Оба исходника сняты в 30 кадрах — для перемотки прокруткой этого мало.
# Тридцать кадров на двухсекундный ролик — это шестьдесят разных картинок
# на весь ход сцены, и шаг между ними виден как ступенька. Достраиваем до
# шестидесяти: разных картинок вдвое больше, шаг вдвое мельче.
#
# Прежнему ролику третьего экрана достройка была противопоказана — межкадровый
# расчёт рвал фон блоками на кустах и разметке. Нынешний проезд считается чисто,
# проверено покадрово, поэтому достраиваются оба.
SMOOTH="minterpolate=fps=60:mi_mode=mci:mc_mode=aobmc:me_mode=bidir:vsbmc=1"

# --- первый экран: под перемотку, без звука ---
#
# Исходник теперь hero-drift.mp4 - ночная сессия на 55 секунд. Перематывать
# прокруткой такую длину нельзя: на экран пришлась бы доля секунды хода,
# и кадр скакал бы. Берётся один непрерывный проезд с 43.6 по 46.1 - машина
# подходит в заносе, проходит под навесом и уходит в дым. Склеек внутри нет:
# перемотка через склейку читается поломкой.
#
# Конец куска выбран заказчиком по кадру: прокрутка должна упираться в момент,
# где машина уже ушла влево, а справа стоит дым. Дальше в исходнике камера
# уезжает в темноту - этот хвост отрезан.
#
# Достраивается до 60 кадров ($SMOOTH). На 30 кадрах перемотка выглядела
# рвано: камера идёт быстро, и между соседними картинками слишком большой шаг.
# Опасение, что дым и смаз пойдут разводами, проверено покадрово - считается
# чисто. Вес за это вырос примерно на треть, и чтобы он не съел прелоадер,
# сжатие на ступень плотнее: crf 25 вместо 23.
#
# 1280, а не 1600: тот же довод про вес. Съёмка ночная и смазанная, мелкой
# фактуры в кадре нет, разницы на глаз не видно.
echo "hero-bg: проезд 43.6-46.1, 60 кадров, сплошные ключевые" >&2
ffmpeg -y -v error -ss 43.6 -t 2.5 -i "$A/hero-drift.mp4" -an \
  -vf "hqdn3d=3:2:4:4,$SMOOTH,scale=1280:720:flags=lanczos+accurate_rnd+full_chroma_int,cas=0.35" \
  -c:v libx264 -preset slow -crf 25 -pix_fmt yuv420p -profile:v high \
  $KEYS -movflags +faststart "$W/hero-bg.mp4"

# --- экран «Движение»: тихая петля, без звука ---
#
# Исходник — motion-drive.mp4, проезд с площадки на шоссе и в ночь. Заказчик
# просил показывать его в 2K, поэтому ширина 2560. Кадр в исходнике 1064×576,
# так что это растяжение в два с половиной раза: пикселей больше, резкости
# не прибавилось. Перед растяжением слабое шумоподавление, после — cas:
# на такой мягкой записи иначе лезет каша, а битрейт уходит на зерно.
#
# Сплошной ключевой кадровки здесь нет и она не нужна. Ролик больше не
# перематывается прокруткой — он идёт петлёй сам, — а под перемотку каждый
# кадр обязан быть ключевым, и четырнадцать секунд в такой ширине стоили
# двадцати шести мегабайт против нынешних восьми.
echo "motion-bg: 2K, петля…" >&2
ffmpeg -y -v error -i "$A/motion-drive.mp4" -an   -vf "hqdn3d=1.5:1:2:2,scale=2560:-2:flags=lanczos+accurate_rnd+full_chroma_int,cas=0.45"   -c:v libx264 -preset slow -crf 22 -pix_fmt yuv420p -profile:v high   -x264-params "aq-mode=3:aq-strength=1.1"   -movflags +faststart "$W/motion-bg.mp4"

# Постер — первый кадр уже пережатой копии, а не оригинала: пока ролик идёт
# по сети, на экране стоит ровно тот кадр, с которого он начнётся, и в цвете
# после кодека они совпадают.
#
# Пересобирается вместе с роликом, иначе после замены остался бы старый кадр.
for w in 2560 1600 1280 828; do
  sfx=""; [ "$w" -ne 2560 ] && sfx="-$w"
  ffmpeg -y -v error -i "$W/motion-bg.mp4" -frames:v 1 -vf "scale=$w:-2" -q:v 80 "$W/motion-open$sfx.webp"
  ffmpeg -y -v error -i "$W/motion-bg.mp4" -frames:v 1 -vf "scale=$w:-2" -q:v 4  "$W/motion-open$sfx.jpg"
done

# --- экран 2: тихая петля из паркинга ---
#
# Этот ролик прокруткой не перематывается — он просто идёт петлёй, пока экран
# в окне. Поэтому ни сплошных ключевых кадров, ни достройки до 60: и то и другое
# нужно было ради перемотки, а здесь только раздуло бы двадцатисекундный файл.
#
# Исходник снят вертикально и лежит повёрнутым на 90°, без метки поворота
# в контейнере — браузер развернул бы его сам только по такой метке, поэтому
# поворачиваем на кодировании. После поворота кадр 1024×576; заказчик просил
# 1920×1080, и растягиваем именно до него, но резкости это не добавляет —
# пикселей в исходнике меньше.
#
# Из этого же следует вся остальная обвязка. Растянутый кадр мягкий, и его
# вытягивает cas — адаптивная резкость, которая, в отличие от unsharp, не даёт
# светлых кайм по контурам. Перед растяжением идёт слабое шумоподавление:
# съёмка тёмная и зернистая, зерно после растяжения становится крупным, ест
# битрейт и читается как «шакальность». aq-mode=3 отдаёт биты тёмным участкам —
# без него чёрный кузов и асфальт рассыпались на ступеньки.
KEYS2="aq-mode=3:aq-strength=1.1:psy-rd=1.0,0.15:deblock=-1,-1"
CLEAN="hqdn3d=1.5:1:2:2,transpose=2"
SHARP="lanczos+accurate_rnd+full_chroma_int"

echo "jzx100-garage: поворот, чистка, два размера…" >&2
ffmpeg -y -v error -i "$A/jzx100-garage.mp4" -an   -vf "$CLEAN,scale=1920:1080:flags=$SHARP,cas=0.5"   -c:v libx264 -preset veryslow -crf 21 -pix_fmt yuv420p -profile:v high   -x264-params "$KEYS2" -movflags +faststart "$W/jzx100-garage.mp4"

# Копия для узких экранов. 1280, а не 960: на телефоне с плотным экраном 960
# уже видно, а разница в весе между ними невелика.
ffmpeg -y -v error -i "$A/jzx100-garage.mp4" -an   -vf "$CLEAN,scale=1280:720:flags=$SHARP,cas=0.5"   -c:v libx264 -preset veryslow -crf 22 -pix_fmt yuv420p -profile:v high   -x264-params "$KEYS2" -movflags +faststart "$W/jzx100-garage-1280.mp4"

# Постер — первый кадр уже пережатой копии: пока ролик идёт по сети, экран
# стоит ровно на том кадре, с которого ролик и начнётся.
for w in 1600 828; do
  sfx=""; [ "$w" -ne 1600 ] && sfx="-$w"
  ffmpeg -y -v error -i "$W/jzx100-garage.mp4" -frames:v 1 -vf "scale=$w:-2" -q:v 85 "$W/jzx100-garage-poster$sfx.webp"
  ffmpeg -y -v error -i "$W/jzx100-garage.mp4" -frames:v 1 -vf "scale=$w:-2" -q:v 3  "$W/jzx100-garage-poster$sfx.jpg"
done

# --- карточки: звук сохраняем, длину не трогаем ---
for n in 1 2; do
  ffmpeg -y -v error -i "$A/card-$n.mp4" \
    -c:v libx264 -preset slow -crf 27 -pix_fmt yuv420p -profile:v high \
    -c:a aac -b:a 96k -ac 2 -movflags +faststart "$W/card-$n.mp4"
done

ls -la "$W"/*.mp4
echo DONE
